std::string Strings::t(std::string_view key, std::string_view param, std::string_view value)
{
    std::string text = lookup(key);
    if (!param.empty()) {
        replaceAll(text, "{" + std::string(param) + "}", std::string(value));
    }
    return text;
}

std::string Strings::t2(std::string_view key,
                        std::string_view p1,
                        std::string_view v1,
                        std::string_view p2,
                        std::string_view v2)
{
    std::string text = lookup(key);
    replaceAll(text, "{" + std::string(p1) + "}", std::string(v1));
    replaceAll(text, "{" + std::string(p2) + "}", std::string(v2));
    return text;
}

std::vector<std::string> Strings::knownKeys(std::string_view localeCode)
{
    const StringTable& table = tableForLocale(localeCode);
    std::vector<std::string> keys;
    keys.reserve(table.size());
    for (const auto& [key, value] : table) {
        keys.push_back(key);
    }
    std::sort(keys.begin(), keys.end());
    return keys;
}

std::string Strings::rawValue(std::string_view localeCode, std::string_view key)
{
    return tableValue(tableForLocale(localeCode), key);
}

std::string Strings::lookup(std::string_view key)
{
    const std::string value = tableValue(tableForLocale(Locale::code()), key);
    if (!value.empty()) {
        return value;
    }
    const std::string fallback = tableValue(tableForLocale(Locale::kDefaultCode), key);
    return fallback.empty() ? std::string(key) : fallback;
}

std::string Strings::bookLanguageLabel(std::string_view code)
{
    const std::string trimmed = trim(code);
    if (trimmed.empty()) {
        return trimmed;
    }
    const std::string key = "book.language." + trimmed;
    const std::string label = lookup(key);
    return label != key ? label : trimmed;
}

