const StringTable& tableForLocale(std::string_view localeCode)
{
    static const StringTable arabic = arabicStrings();
    static const StringTable french = frenchStrings();
    static const StringTable english = englishStrings();

    if (localeCode == "fr") {
        return french;
    }
    if (localeCode == "en") {
        return english;
    }
    return arabic;
}

std::string tableValue(const StringTable& table, std::string_view key)
{
    const auto it = table.find(std::string(key));
    return it == table.end() ? std::string() : it->second;
}

